"""Create the bundled offline catalog from the official IBGE Localidades API responses."""
import json,sys,hashlib
from pathlib import Path
states=json.loads(Path(sys.argv[1]).read_text())
municipalities=json.loads(Path(sys.argv[2]).read_text())
by_id={s['id']:{'id':s['id'],'uf':s['sigla'],'name':s['nome'],'cities':[]} for s in states}
for m in municipalities:
 uf=m.get('microrregiao') or {}
 uf=(uf.get('mesorregiao') or {}).get('UF') or ((m.get('regiao-imediata') or {}).get('regiao-intermediaria') or {}).get('UF')
 assert uf and uf['id'] in by_id, m
 by_id[uf['id']]['cities'].append([str(m['id']),m['nome']])
assert len(by_id)==27 and len(municipalities)>=5570
assert len({m['id'] for m in municipalities})==len(municipalities)
data={'source':'https://servicodados.ibge.gov.br/api/v1/localidades/municipios?orderBy=nome','retrieved':'2026-10-17','states':sorted(by_id.values(),key=lambda s:s['name'])}
text='/* Official IBGE Localidades snapshot; generated by tools/prepare_cities.py. */\n(function(root){const data='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';if(typeof module!=="undefined")module.exports=data;root.RptGeo=data;})(typeof window==="undefined"?globalThis:window);\n'
Path(sys.argv[3]).write_text(text)
print('OFFLINE CATALOG:',len(by_id),'UFs;',len(municipalities),'municipalities;',len(text.encode()),'bytes')
